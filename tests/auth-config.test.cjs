const fs = require('fs');
const assert = require('assert');
const rules = JSON.parse(fs.readFileSync('platform/database.rules.spark.json', 'utf8')).rules;
const index = fs.readFileSync('workshop.html', 'utf8');
const catalog = fs.readFileSync('catalog.html', 'utf8');
const auth = fs.readFileSync('assets/js/auth.js', 'utf8');
const config = fs.readFileSync('assets/js/firebase-config.js', 'utf8');
const core = fs.readFileSync('assets/js/core.js', 'utf8');
const catalogJs = fs.readFileSync('assets/js/catalog-page.js', 'utf8');

assert.ok(index.includes('assets/js/auth.js') && catalog.includes('assets/js/auth.js'));
assert.ok(auth.includes('signInWithEmailAndPassword'));
assert.ok(auth.includes('userTenantIndex/${user.uid}'));
assert.ok(auth.includes('tenantMemberships/${tenantId}/${user.uid}'));
assert.ok(auth.includes('tenants/${this.tenantId}/workshopData'));
assert.ok(!auth.includes('userRoles/'));
assert.ok(config.includes('alisabersystem-staging'));
assert.ok(core.includes('AuthModule.dataRef()') && !core.includes("db.ref('ali_saber_system_data')"));
assert.ok(catalogJs.includes('AuthModule.dataRef()') && !catalogJs.includes("db.ref('ali_saber_system_data')"));
assert.ok(rules.userTenantIndex.$uid['.read'].includes('auth.uid == $uid'));
assert.ok(rules.userTenantIndex.$uid['.write'].includes('platformAdmin'));
assert.ok(rules.tenants.$tenantId.workshopData['.read'].includes('tenantMemberships'));
assert.ok(rules.tenants.$tenantId.workshopData['.write'].includes("role').val() == 'owner'"));
console.log('Unified staging auth and tenant isolation checks passed.');
